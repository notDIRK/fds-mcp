# 3. the schema describes the router we think it does
# ==========================================================================

def test_schema_resources_match_registered_routers():
    """No token needed — the schema is public.

    drf-spectacular generates it from the live router, so the set of first path segments
    under ``/api/v1/`` is the set of registered resources. There is no documentation
    delta to allow for.
    """
    response = httpx.get(
        f"{config.api_url()}/schema/",
        headers={"User-Agent": USER_AGENT,
                 "Accept": "application/vnd.oai.openapi+json, application/json"},
        timeout=TIMEOUT,
        follow_redirects=True,
    )
    assert response.status_code == 200, response.text[:500]
    try:
        schema = response.json()
    except ValueError:  # the endpoint also serves YAML
        schema = yaml.safe_load(response.text)

    resources = {path.split("/")[3] for path in schema["paths"]
                 if path.startswith("/api/v1/") and len(path.split("/")) > 3}
    assert resources == set(EXPECTED_RESOURCES), {
        "new": sorted(resources - EXPECTED_RESOURCES),
        "gone": sorted(EXPECTED_RESOURCES - resources),
    }


def test_schema_message_endpoint_still_has_no_email_path():
    """A second reading of the same schema: no resource offers an e-mail reply.

    Guards the gap from the other side. ``/api/v1/message/`` exists and accepts POST —
    the restriction lives in the serializer, not in the router — so the router alone
    cannot tell us the channel is closed. What it can tell us is that no *other*
    resource has appeared to open one.
    """
    response = httpx.get(
        f"{config.api_url()}/schema/",
        headers={"User-Agent": USER_AGENT,
                 "Accept": "application/vnd.oai.openapi+json, application/json"},
        timeout=TIMEOUT,
        follow_redirects=True,
    )
    assert response.status_code == 200
    try:
        schema = response.json()
    except ValueError:
        schema = yaml.safe_load(response.text)

    assert "/api/v1/message/" in schema["paths"]
    assert "post" in schema["paths"]["/api/v1/message/"]
    reply_paths = [p for p in schema["paths"]
                   if any(word in p for word in ("reply", "send", "email"))]
    assert reply_paths == [], reply_paths
